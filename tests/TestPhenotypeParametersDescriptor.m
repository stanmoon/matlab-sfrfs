        function testIndexOfReturnsInsertionIndex(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            p.addParam(name="a", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Bool);
            p.addParam(name="b", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Bool);
            p.addParam(name="c", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Bool);

            testCase.verifyEqual(p.indexOf("a"), 1);
            testCase.verifyEqual(p.indexOf("b"), 2);
            testCase.verifyEqual(p.indexOf("c"), 3);
        end

        function testGetParamByNameMatchesGetParam(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            p.addParam( ...
                name="x", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Real, ...
                lo=0, hi=1);

            s1 = p.getParam(1);
            s2 = p.getParamByName("x");

            schema = epistemic.tools.evolutionary.phenotype.structs. ...
                PhenotypeParameterSchema;

            testCase.verifyEqual(s1, s2);
            testCase.verifyEqual(s2.(schema.NAME), "x");
        end

        function testNamesReturnsInInsertionOrder(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            testCase.verifyEqual(p.names(), string.empty(1, 0));

            p.addParam(name="b", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Bool);
            p.addParam(name="a", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Bool);

            testCase.verifyEqual(p.names(), ["b","a"]);
        end

