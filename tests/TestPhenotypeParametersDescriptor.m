        function testConstructorEmpty(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            testCase.verifyEqual(p.nParams(), 0);

            a = p.toArray();
            testCase.verifyEqual(numel(a), 0);
            testCase.verifyTrue(isstruct(a));
        end

