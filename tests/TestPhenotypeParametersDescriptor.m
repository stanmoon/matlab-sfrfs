        function testHasParamReflectsPresence(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            testCase.verifyFalse(p.hasParam("x"));

            p.addParam( ...
                name="x", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Real, ...
                lo=0, hi=1);

            testCase.verifyTrue(p.hasParam("x"));
            testCase.verifyFalse(p.hasParam("y"));
        end

