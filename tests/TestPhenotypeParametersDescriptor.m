        function testAddRealStoresBoundsInDomain(testCase)
            p = epistemic.tools.evolutionary.phenotype. ...
                PhenotypeParametersDescriptor();

            p.addParam( ...
                name="\Sigma_1", ...
                kind=epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Real, ...
                lo=5, ...
                hi=10, ...
                shape=[1 1]);

            testCase.verifyEqual(p.nParams(), 1);

            spec = p.getParam(1);
            schema = epistemic.tools.evolutionary.phenotype.structs. ...
                PhenotypeParameterSchema;

            testCase.verifyEqual(spec.(schema.NAME), "\Sigma_1");
            testCase.verifyEqual(spec.(schema.KIND), ...
                epistemic.tools.evolutionary.phenotype. ...
                    PhenotypeParameterKind.Real);
            testCase.verifyEqual(spec.(schema.SHAPE), [1 1]);

            dom = spec.(schema.DOMAIN);
            testCase.verifyTrue(isfield(dom, "lo"));
            testCase.verifyTrue(isfield(dom, "hi"));
            testCase.verifyEqual(dom.lo, 5);
            testCase.verifyEqual(dom.hi, 10);
            testCase.verifyFalse(isfield(dom, "bounds"));
        end

