        function testMode1ValidConstructionWithMasks(testCase)
            % New interface: buildSFRFsParameters
            pNoSidebands = SFRFsParameters.buildSFRFsParameters( ...
                order=3, numSidebands=0, numHarmonics=8, ...
                centerMask = ...
                GaussianMaskParameters('bandwidth',5,'sigmaRule',7), ...
                surroundMask = ...
                GaussianMaskParameters('bandwidth',12,'sigmaRule',3), ...
                inhibitionFactor=0.6);
        
            pFull = SFRFsParameters.buildSFRFsParameters( ...
                order=3, numSidebands=4, numHarmonics=8, ...
                centerMask = ...
                GaussianMaskParameters('bandwidth',5,'sigmaRule',7), ...
                surroundMask = ...
                SuperGaussianMaskParameters('alpha',12,'beta',4), ...
                inhibitionFactor=0.6);
        
            obj = SFRFsParametersRollingBearings( ...
                'outerRace', pNoSidebands, ...
                'innerRace', pFull, ...
                'ball',      pFull, ...
                'cage',      pNoSidebands);
        
            testCase.verifyEqual(obj.outerRace, pNoSidebands);
            testCase.verifyEqual(obj.innerRace, pFull);
            testCase.verifyEqual(obj.ball, pFull);
            testCase.verifyEqual(obj.cage, pNoSidebands);
        
            % Sanity: mask objects exist and are MaskParameters
            testCase.verifyTrue( ...
                isa(obj.innerRace.centerMask, 'MaskParameters'));
            testCase.verifyTrue( ...
                isa(obj.innerRace.surroundMask, 'MaskParameters'));
        end
        
        function testMode2ValidConstructionWithMasks(testCase)
            % SameForAllFaultTypes with mask interface
            shared = SFRFsParameters.buildSFRFsParameters( ...
                order = 3, ...
                numSidebands = 4 , ...
                numHarmonics = 8, ...
                centerMask = ...
                GaussianMaskParameters('bandwidth',5,'sigmaRule',7), ...
                surroundMask = ...
                SuperGaussianMaskParameters('alpha',12,'beta',4), ...
                inhibitionFactor = 0.6);
        
            obj = SFRFsParametersRollingBearings( ...
                'SameForAllFaultTypes', shared);
        
            % OuterRace and Cage must be forced to 0 sidebands
            testCase.verifyEqual(obj.outerRace.numSidebands, 0);
            testCase.verifyEqual(obj.cage.numSidebands, 0);
        
            % Inner + Ball preserve shared sidebands
            testCase.verifyEqual( ...
                obj.innerRace.numSidebands, shared.numSidebands);
            testCase.verifyEqual( ...
                obj.ball.numSidebands, shared.numSidebands);
        
            % Masks preserved
            testCase.verifyTrue( ...
                isa(obj.innerRace.centerMask, 'MaskParameters'));
            testCase.verifyTrue(isa( ...
                obj.innerRace.surroundMask, 'MaskParameters'));
        end
        
