        function testMode1LegacyParamsShouldPass(testCase)
        % Legacy constructor output should be accepted.

            pNoSb = SFRFsParameters.createSFRFsParameters( ...
                'order', 1, 'numSidebands', 0, 'numHarmonics', 8, ...
                'sigmaCenter', [5 7], 'sigmaSurround', [12 3], ...
                'inhibitionFactor', 0.6);

            pOk = SFRFsParameters.createSFRFsParameters( ...
                'order', 2, 'numSidebands', 4, 'numHarmonics', 8, ...
                'sigmaCenter', [5 7], 'sigmaSurround', [12 3], ...
                'inhibitionFactor', 0.6);

            obj = SFRFsParametersRollingBearings( ...
                'outerRace', pNoSb, ...
                'innerRace', pOk, ...
                'ball',      pOk, ...
                'cage',      pNoSb);

            testCase.verifyEqual(obj.outerRace, pNoSb);
            testCase.verifyEqual(obj.innerRace, pOk);
            testCase.verifyEqual(obj.ball,      pOk);
            testCase.verifyEqual(obj.cage,      pNoSb);
        end


