classdef TestLiftedHarmonicGainFunctions < matlab.unittest.TestCase
% TestLiftedHarmonicGainFunctions
%
% Unit tests for LiftedHarmonicGainFunctions:
% - construction
% - harmonic table creation
% - center/surround mask geometry
% - selected harmonic preservation
% - validation behavior

    methods(Test)

        function testValidConstruction(testCase)
            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();

            obj = LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = [1; 2; 3]);

            testCase.verifyEqual(obj.characteristicFrequencyHz, 100);
            testCase.verifyEqual(obj.harmonicIndices, [1; 2; 3]);
            testCase.verifyEqual(string(obj.faultType), string(ft));
        end

        function testComputeCreatesTable(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                harmonicIndices = [1; 2; 4]);

            obj.compute();

            tbl = obj.liftedGainFunctionsTable;

            testCase.verifyEqual(height(tbl), 3);
            testCase.verifyTrue(istable(tbl));
            testCase.verifyTrue(any(tbl.Properties.VariableNames == ...
                "HarmonicIndex"));
            testCase.verifyTrue(any(tbl.Properties.VariableNames == ...
                "FrequencyBankMasks"));
        end

        function testHarmonicFrequenciesAreCorrect(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                characteristicFrequencyHz = 50, ...
                harmonicIndices = [1; 3; 5]);

            obj.compute();

            act = obj.liftedGainFunctionsTable.CenterFrequencyHz;
            exp = [50; 150; 250];

            testCase.verifyEqual(act, exp);
        end

        function testMasksHaveFrequencyDomainSize(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                harmonicIndices = [1; 2]);

            obj.compute();

            f = obj.frequencyDomain;
            tbl = obj.liftedGainFunctionsTable;

            for i = 1:height(tbl)
                masks = tbl.FrequencyBankMasks{i};

                testCase.verifySize(masks.CenterMask, size(f));
                testCase.verifySize(masks.SurroundMask, size(f));
            end
        end

        function testMasksAreBounded(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                harmonicIndices = [1; 2; 3]);

            obj.compute();

            tbl = obj.liftedGainFunctionsTable;

            for i = 1:height(tbl)
                masks = tbl.FrequencyBankMasks{i};

                testCase.verifyGreaterThanOrEqual(masks.CenterMask, 0);
                testCase.verifyLessThanOrEqual(masks.CenterMask, 1);

                testCase.verifyGreaterThanOrEqual(masks.SurroundMask, 0);
                testCase.verifyLessThanOrEqual(masks.SurroundMask, 1);
            end
        end

        function testCenterAndSurroundBandsUseAlphas(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = 2);

            obj.compute();

            tbl = obj.liftedGainFunctionsTable;

            centerBand = tbl.CenterBandHz{1};
            surroundBand = tbl.SurroundBandHz{1};

            testCase.verifyEqual(centerBand, [198, 202], ...
                "AbsTol", 1e-12);

            testCase.verifyEqual(surroundBand, [194, 206], ...
                "AbsTol", 1e-12);
        end

        function testSelectedHarmonicsArePreserved(testCase)
            h = [1; 2; 5];
        
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                harmonicIndices = h);
        
            obj.compute();
        
            act = obj.liftedGainFunctionsTable.HarmonicIndex;
        
            testCase.verifyEqual(act, h);
        end

        function testFrequencyDomainIsStored(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject();

            obj.compute();

            exp = obj.snapshotParameters.getFrequencyDomain();
            act = obj.frequencyDomain;

            testCase.verifyEqual(act, exp(:));
        end

        function testNegativeCharacteristicFrequencyThrows(testCase)
            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();

            testCase.verifyError(@() LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = -100, ...
                harmonicIndices = [1; 2]), ...
                "MATLAB:validators:mustBePositive");
        end

        function testNonIntegerHarmonicThrows(testCase)
            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();

            testCase.verifyError(@() LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = [1; 2.5]), ...
                "MATLAB:validators:mustBeInteger");
        end

        function testZeroHarmonicThrows(testCase)
            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();

            testCase.verifyError(@() LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = [0; 1]), ...
                "MATLAB:validators:mustBePositive");
        end


        function testComputeMaxHarmonicIndexUsesNyquist(testCase)
            sp = ParametersSnapshot( ...
                samplingFrequency = 1024, ...
                duration = 1, ...
                stride = 1);
        
            H = LiftedHarmonicGainFunctions.computeMaxHarmonicIndex( ...
                snapshotParameters = sp, ...
                characteristicFrequencyHz = 100);
        
            testCase.verifyEqual(H, 5);
        end
        
        function testEmptyHarmonicsAutoResolve(testCase)
            obj = TestLiftedHarmonicGainFunctions.makeObject( ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = []);
        
            testCase.verifyEqual(obj.harmonicIndices, (1:5).');
        end
        
        function testRequestedHarmonicsAboveMaximumThrow(testCase)
            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();
        
            testCase.verifyError(@() LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = 100, ...
                harmonicIndices = [1; 2; 6]), ...
                "sfrfs:LiftedHarmonicGainFunctions:HarmonicRange");
        end
        
        function testComputeMaxHarmonicIndexThrowsWhenNoSupport(testCase)
            sp = ParametersSnapshot( ...
                samplingFrequency = 1024, ...
                duration = 1, ...
                stride = 1);
        
            testCase.verifyError(@() ...
                LiftedHarmonicGainFunctions.computeMaxHarmonicIndex( ...
                    snapshotParameters = sp, ...
                    characteristicFrequencyHz = 2048), ...
                "sfrfs:LiftedHarmonicGainFunctions:NoHarmonics");
        end

    end

    methods(Static, Access = private)

        function obj = makeObject(args)
            arguments
                args.characteristicFrequencyHz (1,1) double = 100
                args.harmonicIndices (:,1) double = [1; 2; 3]
            end

            [sp, sfrfsParams, ft, sel] = ...
                TestLiftedHarmonicGainFunctions.fixture();

            obj = LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = ...
                    args.characteristicFrequencyHz, ...
                harmonicIndices = args.harmonicIndices);
        end

        function [sp, sfrfsParams, ft, sel] = fixture()
            sp = ParametersSnapshot( ...
                samplingFrequency = 1024, ...
                duration = 1, ...
                stride = 1);

            sharedParams = SFRFsParameters.buildSFRFsParameters( ...
                order = 0, ...
                numSidebands = 0, ...
                numHarmonics = 3, ...
                centerMask = SuperGaussianMaskParameters( ...
                    alpha = 2, ...
                    beta = 8), ...
                surroundMask = SuperGaussianMaskParameters( ...
                    alpha = 6, ...
                    beta = 2), ...
                inhibitionFactor = 0.9);

            sfrfsParams = SFRFsParametersRollingBearings( ...
                SameForAllFaultTypes = sharedParams);

            ft = SFRFsParametersRollingBearings ...
                .OUTER_RACE_FAULT_TYPE_NAME;

            sel = OperatingConditionSelection( ...
                speed = 35, ...
                load = 12);
        end

    end
end