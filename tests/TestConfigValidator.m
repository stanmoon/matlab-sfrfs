classdef TestConfigValidator < matlab.unittest.TestCase
% TestConfigValidator
%
% Unit tests for:
%   epistemic.tools.evolutionary.internal.ConfigValidator

    methods (Test)

        function ValidateAll_Passes(testCase)

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                0.01, ...
                1.5, ...
                1.0e-10));
        end

        function ValidateAll_BadPopulation_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                0, ...
                100, ...
                0.01, ...
                1.5, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:BadPopulationSize");
        end

        function ValidateAll_BadMaxGenerations_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                0, ...
                0.01, ...
                1.5, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:BadMaxGenerations");
        end

        function ValidateAll_BadMutationRateShape_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                [0.01 0.02], ...
                1.5, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:BadMutationRate");
        end

        function ValidateAll_MutationRateBelowRange_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                -0.01, ...
                1.5, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:MutationRateOutOfRange");
        end

        function ValidateAll_MutationRateAboveRange_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                1.01, ...
                1.5, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:MutationRateOutOfRange");
        end

        function ValidateAll_BadPowerLawAlpha_Throws(testCase)

