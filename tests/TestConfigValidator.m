                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                0.01, ...
                0, ...
                1.0e-10), ...
                "sfrfs:ConfigValidator:BadPowerLawAlpha");
        end

        function ValidateAll_BadPowerLawRMin_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateAllConfigurationParameters( ...
                100, ...
                100, ...
                0.01, ...
                1.5, ...
                0), ...
                "sfrfs:ConfigValidator:BadPowerLawRMin");
        end

        function PopulationSize_PositiveInteger_Passes(testCase)

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validatePopulationSizeIsPositiveIntegerScalar(1));
        end

        function PopulationSize_Invalid_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validatePopulationSizeIsPositiveIntegerScalar(0), ...
                "sfrfs:ConfigValidator:BadPopulationSize");

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validatePopulationSizeIsPositiveIntegerScalar(2.5), ...
                "sfrfs:ConfigValidator:BadPopulationSize");
        end

        function MaxGenerations_PositiveInteger_Passes(testCase)

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMaxGenerationsIsPositiveIntegerScalar(1));
        end

        function MaxGenerations_Invalid_Throws(testCase)

