                "sfrfs:ConfigValidator:BadMaxGenerations");

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMaxGenerationsIsPositiveIntegerScalar(3.2), ...
                "sfrfs:ConfigValidator:BadMaxGenerations");
        end

        function MutationRate_FiniteScalar_Passes(testCase)

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateMutationRateIsNumericScalar( ...
                0.01));
        end

        function MutationRate_NotScalar_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator.validateMutationRateIsNumericScalar( ...
                [0.01 0.02]), ...
                "sfrfs:ConfigValidator:BadMutationRate");
        end

        function MutationRate_UnitInterval_Passes(testCase)

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMutationRateIsWithinClosedUnitInterval(0));

            testCase.verifyWarningFree(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMutationRateIsWithinClosedUnitInterval(1));
        end

        function MutationRate_OutOfRange_Throws(testCase)

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMutationRateIsWithinClosedUnitInterval(-eps), ...
                "sfrfs:ConfigValidator:MutationRateOutOfRange");

            testCase.verifyError(@() ...
                epistemic.tools.evolutionary.internal. ...
                ConfigValidator. ...
                validateMutationRateIsWithinClosedUnitInterval( ...
                1 + eps), ...
                "sfrfs:ConfigValidator:MutationRateOutOfRange");
        end

