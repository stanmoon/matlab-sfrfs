        function testResponseBinderIsApplied(testCase)
            [sp, lifted, memberTable, spectralColumn] = ...
                TestLiftedHarmonicResponseCompute.fixture();
        
            obj = LiftedHarmonicResponseCompute( ...
                snapshotParameters = sp, ...
                liftedGainFunctions = lifted);
        
            binder = @(mask) @(X, f) ...
                trapz(f, abs(X), 1) ./ trapz(f, mask(:));
        
            responses = obj.compute( ...
                memberTable = memberTable, ...
                spectralColumn = spectralColumn, ...
                receptiveFieldResponseBinder = binder);
        
            f = lifted.frequencyDomain;
        
            X = TestLiftedHarmonicResponseCompute.stackSpectra( ...
                memberTable.(spectralColumn));
        
            tbl = lifted.liftedGainFunctionsTable;
        
            for i = 1:height(tbl)
                masks = tbl.FrequencyBankMasks{i};
        
                rfC = binder(masks.CenterMask(:));
                rfS = binder(masks.SurroundMask(:));
        
                nFFT = size(X, 1);

                expC = rfC((masks.CenterMask(:) .* X) ./ nFFT, f).';
                expS = rfS((masks.SurroundMask(:) .* X) ./ nFFT, f).';
        
                testCase.verifyEqual( ...
                    responses.Center(:, i), ...
                    expC, ...
                    "AbsTol", 1e-12);
        
                testCase.verifyEqual( ...
                    responses.Surround(:, i), ...
                    expS, ...
                    "AbsTol", 1e-12);
            end
        end
        
