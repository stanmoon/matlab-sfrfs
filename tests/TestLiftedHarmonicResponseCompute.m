    methods(Static, Access = private)

        function [sp, lifted, memberTable, spectralColumn] = fixture(args)
            arguments
                args.characteristicFrequencyHz (1,1) double = 50
                args.harmonicIndices (:,1) double = [1; 2; 4]
            end

            sp = ParametersSnapshot( ...
                samplingFrequency = 512, ...
                duration = 1, ...
                stride = 1);

            sharedParams = SFRFsParameters.buildSFRFsParameters( ...
                order = 0, ...
                numSidebands = 0, ...
                numHarmonics = 4, ...
                centerMask = SuperGaussianMaskParameters( ...
                    alpha = 2, ...
                    beta = 8), ...
                surroundMask = SuperGaussianMaskParameters( ...
                    alpha = 6, ...
                    beta = 2), ...
                inhibitionFactor = 0.9);

            sfrfsParams = SFRFsParametersRollingBearings( ...
                SameForAllFaultTypes = sharedParams);

            ft = SFRFsParametersRollingBearings ...
                .OUTER_RACE_FAULT_TYPE_NAME;

            sel = OperatingConditionSelection( ...
                speed = 35, ...
                load = 12);

            lifted = LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ft, ...
                selection = sel, ...
                characteristicFrequencyHz = ...
                    args.characteristicFrequencyHz, ...
                harmonicIndices = args.harmonicIndices);

            lifted.compute();

            f = sp.getFrequencyDomain();
            nSnapshots = 5;

            spectra = cell(nSnapshots, 1);

            for j = 1:nSnapshots
                phase = 2*pi*j*f ./ max(f + eps);

                spectra{j} = complex( ...
                    sin(phase), ...
                    cos(phase));
            end

            spectralColumn = "SyntheticFFT";

            memberTable = table( ...
                (1:nSnapshots).', ...
                spectra, ...
                'VariableNames', {'SnapshotIndex', char(spectralColumn)});
        end

        function X = stackSpectra(spectra)
            if ~iscell(spectra)
                X = spectra;
                return
            end

            nSnapshots = numel(spectra);
            nBins = numel(spectra{1});

            X = zeros(nBins, nSnapshots, "like", spectra{1});

            for i = 1:nSnapshots
                X(:, i) = spectra{i}(:);
            end
        end

        function r = verifyFrequencyAxisAndReturnZeros(X, f, expectedF)
            if ~isequal(f(:), expectedF(:))
                error( ...
                    "sfrfs:TestLiftedHarmonicResponseCompute:" + ...
                    "UnexpectedFrequencyAxis", ...
                    "Unexpected frequency axis.");
            end

            r = zeros(1, size(X, 2));
        end

    end
