        end

        function fromRealDecodesCircularly(testCase)
            spec = testCase.makeIntSpec_([1 6], 3, 6);

            G = [-1.6 -1.5 -1.4 0.4 0.5 0.6];

            lo = min(G(:));
            hi = max(G(:));

            block = epistemic.tools.evolutionary.genomes. ...
                RealMetagenomeBlock( ...
                nIndividuals=1, ...
                nAtoms=6, ...
                lo=lo, ...
                hi=hi, ...
                value=G);

            actual = epistemic.tools.evolutionary.phenotype. ...
                decoders.IntDecoders.fromReal(block, spec);

            lo = spec.domain.lo;
            hi = spec.domain.hi;
            L = hi - lo + 1;

            Y = lo + mod(double(G) - lo, L);
            expected = round(Y - 0.5);

            testCase.verifyEqual(actual, expected);
        end

