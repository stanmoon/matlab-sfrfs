    end

    methods (Access = private)

        function spec = makeIntSpec_(~, shape, lo, hi)
            spec = struct();
            spec.shape = shape;
            spec.domain = struct();
            spec.domain.lo = lo;
            spec.domain.hi = hi;
        end

    end

