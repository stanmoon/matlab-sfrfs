        function testSetAtomsUpdatesSelectedAtomsOnlyWithVector(testCase)
        
            G0 = [ ...
                0.5, 1.0 * exp(1i * pi / 3), 1.5; ...
                0.75 * exp(-1i * pi / 4), 1.25, 2.0];
        
            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=3, ...
                lo=0.5, hi=2.0, value=G0);
        
            values = [ ...
                0.6 * exp(-1i * pi / 6), ...
                1.8 * exp( 1i * pi / 2)];
        
            b.setAtoms( ...
                individualIndex=1, ...
                atomIndices=[1; 3], ...
                values=values);
        
            G = b.asMatrix();
        
            testCase.verifyEqual(G(1, [1 3]), values);
            testCase.verifyEqual(G(1, 2), G0(1, 2));
            testCase.verifyEqual(G(2, :), G0(2, :));
        end

        function testSetAtomsReplicatesScalarValue(testCase)
            G0 = [ ...
                0.5, 1.0 * exp(1i * pi / 3), 1.5; ...
                0.75 * exp(-1i * pi / 4), 1.25, 2.0];

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=3, ...
                lo=0.5, hi=2.0, value=G0);

            z = 1.2 * exp(1i * pi / 5);

            b.setAtoms( ...
                individualIndex=2, ...
                atomIndices=[1; 2], ...
                values=z);

            G = b.asMatrix();

            testCase.verifyEqual(G(2, [1 2]), [z z]);
            testCase.verifyEqual(G(2, 3), G0(2, 3));
            testCase.verifyEqual(G(1, :), G0(1, :));
        end

        function testSetAtomsRejectsBelowDomain(testCase)
            b = epistemic.tools.evolutionary.genomes. ...
