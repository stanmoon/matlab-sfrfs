                "sfrfs:ComplexMetagenomeBlock:BadArg");
        end

        function testValueMustRespectAnnulusBounds(testCase)
            G0 = [0.1, 1.5];

            f = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=2, ...
                lo=0.5, hi=1.0, value=G0);

            testCase.verifyError(f, ...
                "sfrfs:ComplexMetagenomeBlock:BadValue");
        end

        function testValueOnAnnulusBoundaryIsAccepted(testCase)
            G0 = [0.5, 1.0 * exp(1i * pi / 3)];

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=2, ...
                lo=0.5, hi=1.0, value=G0);

            G = b.asMatrix();

            testCase.verifyEqual(G, G0);
        end

        function testStoresDeclaredDomain(testCase)
            lo = 0.5;
            hi = 2.0;

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=5, nAtoms=6, lo=lo, hi=hi);

            testCase.verifyEqual(b.lo, lo);
            testCase.verifyEqual(b.hi, hi);
        end

        function testStoresDeclaredDomainWhenValueProvided(testCase)
            G0 = [1+1i, 2+0i; 0.5-0.5i, -1i];

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=2, ...
                lo=0, hi=2.1, value=G0);

            testCase.verifyEqual(b.asMatrix(), G0);
            testCase.verifyEqual(b.lo, 0);
            testCase.verifyEqual(b.hi, 2.1);
        end

        function testGetAtomsReturnsSelectedRowLocalValues(testCase)
            G0 = [ ...
                0.5, 1.0 * exp(1i * pi / 3), 1.5; ...
                0.75 * exp(-1i * pi / 4), 1.25, 2.0];

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=3, ...
                lo=0.5, hi=2.0, value=G0);

            values = b.getAtoms( ...
                individualIndex=2, ...
                atomIndices=[1; 3]);

            testCase.verifyEqual(values, G0(2, [1 3]));
        end

        function testGetAtomsRejectsBadIndividualIndex(testCase)
            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=3, ...
                lo=0.5, hi=2.0);

            f = @() b.getAtoms( ...
                individualIndex=0, ...
                atomIndices=[1; 2]);

            testCase.verifyError(f, ...
                "sfrfs:ComplexMetagenomeBlock:BadArg");
        end

        function testGetAtomsRejectsBadAtomIndices(testCase)
            b = epistemic.tools.evolutionary.genomes. ...
