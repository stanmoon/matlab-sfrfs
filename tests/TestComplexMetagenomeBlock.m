classdef TestComplexMetagenomeBlock < matlab.unittest.TestCase
    methods (Test)

        function testValueCreatesGivenComplexMatrix(testCase)
            G0 = [1+1i, 2+0i; 0.5-0.5i, -1i];

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=2, ...
                lo=0, hi=2.1, value=G0);

            G = b.asMatrix();

            testCase.verifySize(G, [2, 2]);
            testCase.verifyEqual(G, G0);
        end

        function testRandomGenerationCreatesMatrixInAnnulus(testCase)
            lo = 0.5;
            hi = 2.0;

            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=5, nAtoms=6, lo=lo, hi=hi);

            G = b.asMatrix();

            testCase.verifySize(G, [5, 6]);
            testCase.verifyClass(G, "double");
            testCase.verifyGreaterThanOrEqual(abs(G), lo);
            testCase.verifyLessThanOrEqual(abs(G), hi);
        end

        function testZeroRadiusCreatesAllZeros(testCase)
            b = epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=3, nAtoms=4, lo=0, hi=0);

            G = b.asMatrix();

            testCase.verifyEqual(G, zeros(3, 4));
        end

        function testNegativeLoThrowsError(testCase)
            f = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=1, lo=-eps, hi=1);

            testCase.verifyError(f, ...
                "sfrfs:ComplexMetagenomeBlock:BadArg");
        end

        function testLoGreaterThanHiThrowsError(testCase)
            f = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=1, lo=2, hi=1);

            testCase.verifyError(f, ...
                "sfrfs:ComplexMetagenomeBlock:BadRange");
        end

        function testValueMustBeFiniteComplexMatrix(testCase)
            f1 = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=1, value=Inf + 1i);

            testCase.verifyError(f1, ...
                "sfrfs:ComplexMetagenomeBlock:BadArg");

            f2 = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=1, nAtoms=1, value=NaN + 1i);

            testCase.verifyError(f2, ...
                "sfrfs:ComplexMetagenomeBlock:BadArg");
        end

        function testValueMustMatchRequestedSize(testCase)
            G0 = [1+1i, 2+2i];

            f = @() epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                nIndividuals=2, nAtoms=2, value=G0);

