        function buildMemberRowsReturnsMatrixChannels(testCase)

            [builder, FFTCols] = ...
                TestContrastPolarityChannelDatasetBuilder.localBuilder();

            memberTable = ...
                TestContrastPolarityChannelDatasetBuilder.localMemberTable();

            rows = builder.buildMemberRows( ...
                memberTable = memberTable, ...
                spectralColumns = FFTCols, ...
                receptiveFieldResponseBinder = ...
                    ReceptiveFieldResponseFunctions.maskedMeanAbs(), ...
                contrastMapping = ContrastMappings.difference(), ...
                quantileLevel = 0, ...
                riseRate = 1, ...
                fallRate = 1);

            for i = 1:height(rows)

                H = rows.HarmonicCount(i);

                testCase.verifySize( ...
                    rows.HorizontalAcceleration_FFT_C{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.VerticalAcceleration_FFT_C{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.ResolvedContrast{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.PolarityReversal{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.OnPositive{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.OnNegative{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.OffPositive{i}, ...
                    [4, H]);

                testCase.verifySize( ...
                    rows.OffNegative{i}, ...
                    [4, H]);
            end

        end

        function buildMemberRowsReturnsAgreementFloorVector(testCase)

            [builder, FFTCols] = ...
                TestContrastPolarityChannelDatasetBuilder.localBuilder();

            memberTable = ...
                TestContrastPolarityChannelDatasetBuilder.localMemberTable();

            rows = builder.buildMemberRows( ...
                memberTable = memberTable, ...
                spectralColumns = FFTCols, ...
                receptiveFieldResponseBinder = ...
                    ReceptiveFieldResponseFunctions.maskedMeanAbs(), ...
                contrastMapping = ContrastMappings.difference(), ...
                quantileLevel = 0, ...
                riseRate = 1, ...
                fallRate = 1);

            for i = 1:height(rows)

                tau = rows.AgreementFloor{i};

                testCase.verifySize(tau, [4, 1]);
                testCase.verifyTrue(all(isfinite(tau)));
                testCase.verifyGreaterThanOrEqual(tau, 0);

            end

        end

        function buildMemberRowsComputesBinaryEventChannels(testCase)

            [builder, FFTCols] = ...
                TestContrastPolarityChannelDatasetBuilder.localBuilder();

            memberTable = ...
                TestContrastPolarityChannelDatasetBuilder.localMemberTable();

            rows = builder.buildMemberRows( ...
                memberTable = memberTable, ...
                spectralColumns = FFTCols, ...
                receptiveFieldResponseBinder = ...
                    ReceptiveFieldResponseFunctions.maskedMeanAbs(), ...
                contrastMapping = ContrastMappings.difference(), ...
                quantileLevel = 0, ...
                riseRate = 1, ...
                fallRate = 1);

            eventNames = [ ...
                "PolarityReversal", ...
                "OnPositive", ...
                "OnNegative", ...
                "OffPositive", ...
                "OffNegative"];

            for i = 1:height(rows)
                for j = 1:numel(eventNames)

                    E = rows.(eventNames(j)){i};

                    testCase.verifyTrue( ...
                        all(E(:) == 0 | E(:) == 1));
                end
            end

        end

        function buildMemberRowsCarriesMetadata(testCase)

            [builder, FFTCols] = ...
                TestContrastPolarityChannelDatasetBuilder.localBuilder();

            memberTable = ...
                TestContrastPolarityChannelDatasetBuilder.localMemberTable();

            rows = builder.buildMemberRows( ...
                memberTable = memberTable, ...
                spectralColumns = FFTCols, ...
                receptiveFieldResponseBinder = ...
                    ReceptiveFieldResponseFunctions.maskedMeanAbs(), ...
                contrastMapping = ContrastMappings.difference(), ...
                quantileLevel = 0, ...
                riseRate = 1, ...
                fallRate = 1);

            testCase.verifyEqual( ...
                rows.Label, ...
                repmat("Bearing1_1", 2, 1));

            testCase.verifyEqual(rows.Speed, repmat(35, 2, 1));
            testCase.verifyEqual(rows.Load, repmat(12, 2, 1));
            testCase.verifyEqual(rows.Lifetime, repmat(4, 2, 1));

            testCase.verifyEqual(rows.Failure_O, ones(2, 1));
            testCase.verifyEqual(rows.Failure_I, zeros(2, 1));
            testCase.verifyEqual(rows.Failure_C, zeros(2, 1));
            testCase.verifyEqual(rows.Failure_B, zeros(2, 1));

        end

    end

    methods (Static, Access = private)

        function [builder, FFTCols] = localBuilder()

            sp = ParametersSnapshot( ...
                samplingFrequency = 25600, ...
                duration = 1.28, ...
                stride = 60);

            bp = ParametersRollingBearings( ...
                numRollingElements = 8, ...
                ballDiameter = 7.92, ...
                pitchDiameter = 34.55, ...
                contactAngle = 0);

            sel = OperatingConditionSelection(speed = 35, load = 12);
            oc = OperatingConditions(35, 12);

            sharedParams = SFRFsParameters.buildSFRFsParameters( ...
                order = 0, ...
                numSidebands = 0, ...
                numHarmonics = 3, ...
                centerMask = SuperGaussianMaskParameters( ...
                    alpha = 2, ...
                    beta = 8), ...
                surroundMask = SuperGaussianMaskParameters( ...
                    alpha = 6, ...
                    beta = 2), ...
                inhibitionFactor = 1);

            sfrfsParams = SFRFsParametersRollingBearings( ...
                SameForAllFaultTypes = sharedParams);

            bfb = BearingFrequencyBands( ...
                bearingParams = bp, ...
                sfrfsParams = sfrfsParams, ...
                operatingConditions = oc);

            ftOuter = string( ...
                SFRFsParametersRollingBearings ...
                    .OUTER_RACE_FAULT_TYPE_NAME);

            ftInner = string( ...
                SFRFsParametersRollingBearings ...
                    .INNER_RACE_FAULT_TYPE_NAME);

            fcOuter = bfb.getCentralFrequency( ...
                BearingFrequencyBands.BPFO_CODE, ...
                sel.speed);

            fcInner = bfb.getCentralFrequency( ...
                BearingFrequencyBands.BPFI_CODE, ...
                sel.speed);

            liftedOuter = LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ftOuter, ...
                selection = sel, ...
                characteristicFrequencyHz = fcOuter, ...
                harmonicIndices = (1:3).');

            liftedInner = LiftedHarmonicGainFunctions( ...
                snapshotParameters = sp, ...
                sfrfsParameters = sfrfsParams, ...
                faultType = ftInner, ...
                selection = sel, ...
                characteristicFrequencyHz = fcInner, ...
                harmonicIndices = (1:3).');

            liftedOuter.compute();
            liftedInner.compute();

            builder = ContrastPolarityChannelDatasetBuilder( ...
                liftedGainFunctionsByFamily = ...
                    {liftedOuter, liftedInner}, ...
                familyNames = ["BPFO", "BPFI"]);

            FFTCols = [ ...
                "HorizontalAcceleration_FFT", ...
                "VerticalAcceleration_FFT"];

        end

        function memberTable = localMemberTable()

            sp = ParametersSnapshot( ...
                samplingFrequency = 25600, ...
                duration = 1.28, ...
                stride = 60);

            n = numel(sp.getFrequencyDomain());

            Label = repmat("Bearing1_1", 4, 1);
            SnapshotIndex = (1:4).';
            Speed = repmat(35, 4, 1);
            Load = repmat(12, 4, 1);
            Lifetime = repmat(4, 4, 1);

            Failure_O = ones(4, 1);
            Failure_I = zeros(4, 1);
            Failure_C = zeros(4, 1);
            Failure_B = zeros(4, 1);

            HorizontalAcceleration_FFT = {
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 1.0)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 2.0)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 0.5)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 3.0)};

            VerticalAcceleration_FFT = {
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 0.5)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 2.5)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 1.5)
                TestContrastPolarityChannelDatasetBuilder ...
                    .localSpectrum(n, 0.2)};

            memberTable = table( ...
                Label, ...
                SnapshotIndex, ...
                Speed, ...
                Load, ...
                Lifetime, ...
                Failure_O, ...
                Failure_I, ...
                Failure_C, ...
                Failure_B, ...
                HorizontalAcceleration_FFT, ...
                VerticalAcceleration_FFT);

        end

        function X = localSpectrum(n, scale)

            X = zeros(n, 1);
            X(100:140) = scale;
            X(200:240) = scale / 2;
            X = complex(X, 0);

        end

    end

