classdef TestContrastPolarityChannelDatasetBuilder < matlab.unittest.TestCase

    methods (Test)

        function exposesExpectedSchemas(testCase)

            testCase.verifyEqual( ...
                ContrastPolarityChannelDatasetBuilder.ChannelNames, ...
                [ ...
                    "ResolvedContrast", ...
                    "PolarityReversal", ...
                    "OnPositive", ...
                    "OnNegative", ...
                    "OffPositive", ...
                    "OffNegative"]);

            testCase.verifyEqual( ...
                ContrastPolarityChannelDatasetBuilder.MatrixLayout, ...
                ["snapshot", "harmonic"]);

        end

        function rawContrastNamesAppendContrastSuffix(testCase)

            names = ...
                ContrastPolarityChannelDatasetBuilder.rawContrastNames( ...
                    ["HorizontalAcceleration_FFT", ...
                     "VerticalAcceleration_FFT"]);

            testCase.verifyEqual( ...
                names, ...
                ["HorizontalAcceleration_FFT_C", ...
                 "VerticalAcceleration_FFT_C"]);

        end

        function buildMemberRowsReturnsOneRowPerFamily(testCase)

            [builder, FFTCols] = ...
                TestContrastPolarityChannelDatasetBuilder.localBuilder();

            memberTable = ...
                TestContrastPolarityChannelDatasetBuilder.localMemberTable();

            rows = builder.buildMemberRows( ...
                memberTable = memberTable, ...
                spectralColumns = FFTCols, ...
                receptiveFieldResponseBinder = ...
                    ReceptiveFieldResponseFunctions.maskedMeanAbs(), ...
                contrastMapping = ContrastMappings.difference(), ...
                quantileLevel = 0, ...
                riseRate = 1, ...
                fallRate = 1);

            testCase.verifyEqual(height(rows), 2);
            testCase.verifyEqual( ...
                rows.MonitoredFaultFamily, ...
                ["BPFO"; "BPFI"]);

        end

