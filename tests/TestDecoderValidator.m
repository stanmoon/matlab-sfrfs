        function MustHaveAtomCountForShape_PassesForMatchingCount(testCase)
            meta = ?epistemic.tools.evolutionary.internal.DecoderValidator;

            shape = [2 3];
            nAtoms = prod(shape);

            blocks = testCase.makeBlocks_(nAtoms);

            for k = 1:numel(blocks)
                testCase.verifyWarningFree(@() ...
                    epistemic.tools.evolutionary.internal. ...
                    DecoderValidator.mustHaveAtomCountForShape( ...
                    meta, blocks{k}, shape));
            end
        end

        function MustHaveAtomCountForShape_ThrowsForMismatch(testCase)
            meta = ?epistemic.tools.evolutionary.internal.DecoderValidator;

