                IntegerMetagenomeBlock( ...
                    nIndividuals=nInd, ...
                    nAtoms=nAtoms, ...
                    lo=1, ...
                    hi=7), ...
                epistemic.tools.evolutionary.genomes. ...
                RealMetagenomeBlock( ...
                    nIndividuals=nInd, ...
                    nAtoms=nAtoms, ...
                    lo=0, ...
                    hi=1), ...
                epistemic.tools.evolutionary.genomes. ...
                ComplexMetagenomeBlock( ...
                    nIndividuals=nInd, ...
                    nAtoms=nAtoms, ...
