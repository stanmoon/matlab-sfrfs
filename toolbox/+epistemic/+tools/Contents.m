% +tools
%
% This package groups epistemic tools, understood as reusable computational
% instruments that support knowledge acquisition, structuring, and
% evaluation under uncertainty.
%
% Tools are treated instrumentally: they generate, transform, or organize
% candidates, hypotheses, representations, or models without committing
% to a specific purpose such as optimization, exploration, or design.
%
% In this sense, tools act as cognitive scaffolding that can be configured
% and composed to induce epistemic structure (e.g., rankings, contrasts,
% trade-offs) over spaces of interest.
%
% Subpackages
% -----------
% evolutionary
%   Evolutionary mechanisms used as epistemic tools, providing
%   population-based generative and evaluative processes driven by
%   variation, selection, and survival.
%
