classdef Mutators
% Mutators
% Minimal dispatch for genome-space mutation operators.
%
% This class provides a registry-based dispatch mechanism that maps a
% concrete metagenome block type to its corresponding mutation operator.
% The entry point is the static method infer, which returns a callable
% mutation function of the form
%   mutateFcn(block, individualIndex, atomIndices).
%
% The dispatch is performed using the fully qualified class name of the
% provided block. Each supported block type is associated with an infer
% function that constructs the appropriate mutation operator using the
% provided configuration object
% (epistemic.tools.evolutionary.EngineConfig).
%
% Supported mappings include:
%   - BooleanMetagenomeBlock     -> BoolMutators
%   - IntegerMetagenomeBlock     -> IntMutators
%   - RealMetagenomeBlock        -> RealMutators
%   - ComplexMetagenomeBlock     -> ComplexMutators
%   - PermutationMetagenomeBlock -> PermMutators
%
% Unsupported block types result in a validation error.
%
% Notes
%   The dispatcher separates mutation topology (when and where mutations
%   occur) from mutation semantics (how values are perturbed). The returned
%   mutateFcn operates directly on the provided block via its public
%   interface.
%
%   This design enables consistent extension by registering new block
%   types and corresponding mutator implementations without modifying the
%   dispatcher logic.

    properties (Constant, Access = private)

        registry = containers.Map( ...
            { ...
                [ ...
                'epistemic.tools.evolutionary.genomes.' ...
                'BooleanMetagenomeBlock' ...
                ], ...
                [ ...
                'epistemic.tools.evolutionary.genomes.' ...
                'IntegerMetagenomeBlock' ...
                ], ...
                [ ...
                'epistemic.tools.evolutionary.genomes.' ...
                'RealMetagenomeBlock' ...
                ], ...
                [ ...
                'epistemic.tools.evolutionary.genomes.' ...
                'ComplexMetagenomeBlock' ...
                ], ...
                [ ...
                'epistemic.tools.evolutionary.genomes.' ...
                'PermutationMetagenomeBlock' ...
                ] ...
            }, ...
            { ...
                @(args) epistemic.tools.evolutionary. ...
                    operators.mutation.BoolMutators.infer(), ...
                @(args) epistemic.tools.evolutionary. ...
                    operators.mutation.IntMutators.infer( ...
                    config=args.config), ...
                @(args) epistemic.tools.evolutionary. ...
                    operators.mutation.RealMutators.infer( ...
                    config=args.config), ...
                @(args) epistemic.tools.evolutionary. ...
                    operators.mutation.ComplexMutators.infer( ...
                    config=args.config), ...
                @(args) epistemic.tools.evolutionary. ...
                    operators.mutation.PermMutators.infer( ...
                    config=args.config) ...
            });

    end

    methods (Static)

        function mutateFcn = infer(args)
            arguments
                args.block (1,1) ...
                    epistemic.tools.evolutionary.genomes. ...
                    MetagenomeBlock
                args.config (1,1) ...
                    epistemic.tools.evolutionary.EngineConfig
            end
        
            key = string(class(args.block));
            map = epistemic.tools.evolutionary.operators.mutation. ...
                Mutators.registry;
        
            epistemic.tools.evolutionary.internal.ValidationUtils. ...
                mustContainKey( ...
                ?epistemic.tools.evolutionary.operators.mutation. ...
                Mutators, ...
                map, ...
                key, ...
                "UnsupportedBlockType", ...
                "Unsupported block type: %s.");
        
            inferFcn = map(key);
            mutateFcn = inferFcn(args);
        end

    end

    methods (Static)

        function raiseComplexUnimplemented()
            helpers.Errors.raise( ...
                classMeta=?epistemic.tools.evolutionary. ...
                    operators.mutation.Mutators, ...
                suffix="ComplexMutatorsUnimplemented", ...
                message="Complex mutation not implemented.");
        end

        function raisePermUnimplemented()
            helpers.Errors.raise( ...
                classMeta=?epistemic.tools.evolutionary. ...
                    operators.mutation.Mutators, ...
                suffix="PermMutatorsUnimplemented", ...
                message="Permutation mutation not implemented.");
        end

    end

end